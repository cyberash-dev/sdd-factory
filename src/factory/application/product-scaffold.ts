function sectionBlock(heading: string, body: string): string {
  return `## ${heading}\n\n${body}\n\n---\n`;
}

export interface BaselineInput {
  readonly slug: string;
  readonly freshnessToken: string;
  readonly commitSha: string;
  readonly date: string;
}

export function partitionRecord(slug: string, date: string): string {
  return [
    "```yaml",
    "---",
    `id: ${slug}`,
    "type: Partition",
    `partition_id: ${slug}`,
    "owner_team: sdd-factory",
    "gate_scope:",
    `  - ${slug}`,
    "dependencies_on_other_partitions: []",
    "default_policy_set:",
    `  - ${slug}:POL-001`,
    `  - ${slug}:POL-002`,
    `id_namespace: ${slug}`,
    "unmodeled_budget:",
    "  current: 0",
    `  baseline_at: "${date}"`,
    "  baseline_value: 0",
    "  trend: monotonic_non_increasing",
    "---",
    "```",
  ].join("\n");
}

export function baselineRecord(input: BaselineInput): string {
  return [
    "```yaml",
    "---",
    `id: ${input.slug}:BL-001`,
    "type: BrownfieldBaseline",
    "lifecycle:",
    "  status: proposed",
    `partition_id: ${input.slug}`,
    "discovery_scope:",
    "  - src",
    "  - tests",
    "  - package.json",
    "  - tsconfig.json",
    "coverage_evidence:",
    "  - kind: git_tree_hash_v1",
    `    reference: ${input.commitSha}`,
    "    note: |",
    "      Greenfield product generated by sdd-factory; the token covers the",
    "      scaffold commit before any product code exists.",
    `freshness_token: ${input.freshnessToken}`,
    `baseline_commit_sha: ${input.commitSha}`,
    "mechanism: git_tree_hash_v1",
    "---",
    "```",
  ].join("\n");
}

export function productSpecSkeleton(input: BaselineInput): string {
  const sections = SDD_SECTIONS.map((heading) => {
    if (heading === "3. Partition") {
      return sectionBlock(heading, partitionRecord(input.slug, input.date));
    }
    if (heading === "4. Brownfield baseline") {
      return sectionBlock(heading, baselineRecord(input));
    }
    return sectionBlock(heading, "none");
  });
  return [`# ${input.slug} product specification`, "", "> Generated by sdd-factory. Version 0.1.0; every record is `proposed` until the pre-authorised approval.", "", "---", "", ...sections].join("\n");
}

export function assumptionsSkeleton(slug: string): string {
  const sections = SDD_SECTIONS.map((heading) => sectionBlock(heading, "none"));
  return [`# ${slug} assumptions (sandbox)`, "", "> ASSUMPTION records minted after approval live here; see spec/spec.md for the approved records.", "", "---", "", ...sections].join("\n");
}
